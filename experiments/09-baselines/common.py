"""common.py — shared infrastructure for the 09-baselines comparison.

Single source of truth for:
  - paths (this folder + 06/07 assets for the Exp08 reference score)
  - the eval-row contract (rows aligned with candidates_eval, offsets 0..399)
  - daily metrics (RankIC / DA / MAPE) with the dense threshold rule
  - prediction save/load (npz, one score array aligned to the eval rows)

Each baseline model writes ONE npz to ``outputs/<name>_pred.npz``:
    {"score": float64 [N_eval], "model": str, "version": str,
     "meta": {...}}

``score`` is the row-level prediction (any monotone scale); the same metric
function computes daily RankIC / DA / MAPE.  The Exp08 pipeline's fused score
is the reference (``reference_F.npz``, generated by save_reference()).
"""
