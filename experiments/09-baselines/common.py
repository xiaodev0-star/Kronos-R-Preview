def save_json(path, obj):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, default=str)


# ---------------------------------------------------------------------------
# Eval row contract
# ---------------------------------------------------------------------------
def load_eval_rows():
    """Load the eval-row metadata + dense threshold (candidates_eval order).

    Returns a dict with date_key / stock_uid / true_logret / quality / offset
    arrays plus dense_threshold (int).  All baseline prediction arrays MUST be
    aligned to this row order.
    """
    c = np.load(W07 / "candidates-eval-k8.npz", allow_pickle=True)
    return {
        "date_key": c["date_key"],
        "stock_uid": c["stock_uid"],
        "true_logret": c["true_logret"].astype(np.float64),
        "quality": c["quality"].astype(bool),
        "offset": c["offset"] if "offset" in c.files else None,
        "dense_threshold": int(c["dense_threshold"][0]),
        "n_rows": int(len(c["stock_uid"])),
    }


def _split_points(dates):
    order = np.argsort(dates, kind="stable")
    sd = dates[order]
    split = np.flatnonzero(sd[1:] != sd[:-1]) + 1
    bounds = np.concatenate([[0], split, [len(sd)]]).astype(np.int64)
    uniq = [str(sd[int(bounds[i])]) for i in range(len(bounds) - 1)]
    return order, bounds, uniq


def daily_rank_ic(score, rows, dense=None):
    dense = dense if dense is not None else rows["dense_threshold"]
    score = np.asarray(score, dtype=np.float64)
    true = np.asarray(rows["true_logret"], dtype=np.float64)
    valid = np.isfinite(score) & np.isfinite(true) & np.asarray(rows["quality"]).astype(bool)
    order, bounds, uniq = _split_points(rows["date_key"])
    s, t, v = score[order], true[order], valid[order]
    out = {}
    for i in range(len(bounds) - 1):
        lo, hi = int(bounds[i]), int(bounds[i + 1])
        m = v[lo:hi]
        c = int(m.sum())
        if c < dense:
            continue
        sv, tv = s[lo:hi][m], t[lo:hi][m]
        out[uniq[i]] = float(spearmanr(sv, tv)[0]) if (c >= 2 and not np.all(sv == sv[0])) else 0.0
    return out


def daily_da(score, rows, dense=None, dir_threshold=0.0):
    """Direction accuracy: (pred > dir_threshold) == (true > 0)."""
    dense = dense if dense is not None else rows["dense_threshold"]
    score = np.asarray(score, dtype=np.float64)
    true = np.asarray(rows["true_logret"], dtype=np.float64)
    valid = np.isfinite(score) & np.isfinite(true) & np.asarray(rows["quality"]).astype(bool)
    order, bounds, uniq = _split_points(rows["date_key"])
    s, t, v = score[order], true[order], valid[order]
    out = {}
    for i in range(len(bounds) - 1):
        lo, hi = int(bounds[i]), int(bounds[i + 1])
        m = v[lo:hi]
        c = int(m.sum())
        if c < dense:
            continue
        out[uniq[i]] = float(np.mean((s[lo:hi][m] > dir_threshold) == (t[lo:hi][m] > 0)))
    return out


def daily_mape(score, rows, dense=None):
    """MAPE in PRICE space: |exp(pred - true) - 1| (matches the project evaluator)."""
    dense = dense if dense is not None else rows["dense_threshold"]
    score = np.asarray(score, dtype=np.float64)
    true = np.asarray(rows["true_logret"], dtype=np.float64)
    valid = np.isfinite(score) & np.isfinite(true) & np.asarray(rows["quality"]).astype(bool)
    order, bounds, uniq = _split_points(rows["date_key"])
    s, t, v = score[order], true[order], valid[order]
    out = {}
    for i in range(len(bounds) - 1):
        lo, hi = int(bounds[i]), int(bounds[i + 1])
        m = v[lo:hi]
        c = int(m.sum())
        if c < dense:
            continue
        out[uniq[i]] = float(np.mean(np.abs(np.exp(s[lo:hi][m] - t[lo:hi][m]) - 1.0)))
    return out


def full_metrics(score, rows, dir_threshold=0.0):
    """Full-400 aggregated metrics for a score array."""
    ic = daily_rank_ic(score, rows)
    da = daily_da(score, rows, dir_threshold=dir_threshold)
    mp = daily_mape(score, rows)
    return {
        "n_dense_dates": len(ic),
        "avg_daily_rank_ic": float(np.mean(list(ic.values()))) if ic else None,
        "avg_da_per_date": float(np.mean(list(da.values()))) if da else None,
        "avg_mape": float(np.mean(list(mp.values()))) if mp else None,
        "dense_threshold": rows["dense_threshold"],
    }


# ---------------------------------------------------------------------------
# Prediction save / load
# ---------------------------------------------------------------------------
def save_predictions(name, score, meta=None, version="v1"):
    """Save a score array aligned to eval rows."""
    score = np.asarray(score, dtype=np.float64)
    if score.ndim != 1:
        raise ValueError(f"score must be 1-D, got {score.shape}")
    path = OUTPUTS / f"{name}_pred.npz"
    np.savez(path, score=score, model=name, version=version, meta=meta or {})
    return path


def load_predictions(name):
    path = OUTPUTS / f"{name}_pred.npz"
    if not path.exists():
        return None
    d = np.load(path, allow_pickle=True)
    return {"score": d["score"].astype(np.float64), "model": d["model"],
            "version": d["version"], "meta": d["meta"].item()}


# ---------------------------------------------------------------------------
# Exp08 reference (the model we compare against)
# ---------------------------------------------------------------------------
def compute_reference_F(rows=None):
    """Recompute the Exp08 fused score F = 0.5 z(6-head ens) + 0.5 z(P6).

    Uses the exact artifacts from 07/06.  Saved once to outputs/reference_F.npz
    so the comparison is self-contained.
    """
    import torch
    from _exp07 import MlpRankHead
    from f0_scores import rank_pct_per_date, z_per_date

    rows = rows if rows is not None else load_eval_rows()
    de = np.load(W07 / "hidden-eval-w512.npz", allow_pickle=True)
    H = torch.from_numpy(de["hidden"].astype(np.float32))
    dates = np.asarray(rows["date_key"])
    ranks = []
    ck = torch.load(str(W07 / "rank-head-seed42.pt"),
                    map_location="cpu", weights_only=False)
    h = MlpRankHead(dim=256, hidden=64, dropout=0.1, loss="soft_spearman")
    h.load_state_dict(ck["head_state"])
    h.eval()
    with torch.no_grad():
        ranks.append(rank_pct_per_date(dates, h(H).numpy().astype(np.float64)))
    ens = np.mean(ranks, axis=0)
    p6 = np.load(W07_C / "p6-eval-scores.npy").astype(np.float64)
    F = 0.5 * z_per_date(dates, ens) + 0.5 * z_per_date(dates, p6)
    return F


def save_reference():
    """Save the Exp08 F score + its metrics as the reference baseline."""
    rows = load_eval_rows()
    F = compute_reference_F(rows)
    save_predictions("reference_Exp08", F, meta={"model": "Exp08 fused F", "version": "f24"})
    m = full_metrics(F, rows)
    save_json(RESULTS / "reference_Exp08_metrics.json", m)
    print(f"[common] reference saved: RankIC {m['avg_daily_rank_ic']:.4f} "
          f"DA {m['avg_da_per_date']:.4f} MAPE {m['avg_mape']:.4f}")
    return m


if __name__ == "__main__":
    save_reference()
